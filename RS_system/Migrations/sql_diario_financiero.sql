-- =====================================================
-- 7. FUNCIÓN: Recalcular totales de la cabecera
-- =====================================================

CREATE OR REPLACE FUNCTION public.fn_recalcular_totales_diario(p_cabecera_id bigint)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_total_ingresos numeric(18,2);
    v_total_egresos  numeric(18,2);
BEGIN
    SELECT
        COALESCE(SUM(CASE WHEN tipo = 1 THEN monto ELSE 0 END), 0),
        COALESCE(SUM(CASE WHEN tipo = 2 THEN monto ELSE 0 END), 0)
    INTO v_total_ingresos, v_total_egresos
    FROM public.diario_financiero_detalles
    WHERE cabecera_id = p_cabecera_id;

    UPDATE public.diario_financiero_cabeceras
    SET total_ingresos = v_total_ingresos,
        total_egresos  = v_total_egresos,
        saldo_dia      = v_total_ingresos - v_total_egresos
    WHERE id = p_cabecera_id;
END;
$$;

COMMENT ON FUNCTION public.fn_recalcular_totales_diario (bigint) IS 'Recalcula total_ingresos, total_egresos y saldo_dia en la cabecera a partir de los detalles.';

